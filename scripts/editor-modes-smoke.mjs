import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
import { chromium } from 'playwright-core';

const browser = await chromium.launch({ channel: 'msedge', headless: true });
const base = process.env.TEST_URL || 'http://127.0.0.1:5187';
try {
  const page = await browser.newPage({ viewport: { width: 1500, height: 1050 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base);
  const core = await page.evaluate(async () => {
    const { ScoreEditor } = await import('/src/editor.js');
    const { parseScore } = await import('/src/score.js');
    const { sampleXML } = await import('/src/sample.js');
    const editor = new ScoreEditor(sampleXML);
    editor.changeMeters([0, 2], 3, 4);
    const meters = [0, 1, 2, 3].map(index => editor.meterAt(index).beats);
    const oneUndo = editor.undoStack.length;
    editor.undo();
    const restored = [0, 1, 2, 3].map(index => editor.meterAt(index).beats);
    editor.deleteNotes(['0:0:0', '0:0:2']);
    const deleted = editor.records.filter(record => record.partIndex === 0 && record.measureIndex === 0).map(record => ({ rest: record.rest, start: record.startBeats, beats: record.durationUnits / record.divisions }));
    const issues = parseScore(editor.serialize()).measureIssues;
    const all = new ScoreEditor(sampleXML);
    all.deleteNotes(all.records.filter(record => record.pitched).map(record => record.id));
    const silent = parseScore(all.serialize());
    all.insertNote(0, { partIndex: 0, voice: '1', staff: '1' }, 0, 60, 1);
    const reinserted = parseScore(all.serialize()).tracks[0].notes.length;
    const polyXML = `<score-partwise><part-list><score-part id="P"><part-name>Test</part-name></score-part></part-list><part id="P"><measure number="1"><attributes><divisions>1</divisions><time><beats>4</beats><beat-type>4</beat-type></time></attributes><note><pitch><step>C</step><octave>4</octave></pitch><duration>4</duration><voice>1</voice><type>whole</type></note><note><chord/><pitch><step>E</step><octave>4</octave></pitch><duration>4</duration><voice>1</voice><type>whole</type></note><backup><duration>4</duration></backup><note><pitch><step>G</step><octave>3</octave></pitch><duration>4</duration><voice>2</voice><type>whole</type></note></measure></part></score-partwise>`;
    const poly = new ScoreEditor(polyXML);
    poly.deleteNotes(['0:0:0']);
    const chord = { notes: poly.records.filter(record => record.pitched).map(record => ({ midi: record.midi, start: record.startBeats, chord: record.chord })), backup: poly.doc.querySelector('backup duration').textContent, issues: parseScore(poly.serialize()).measureIssues };
    const tied = new ScoreEditor(sampleXML);
    tied.changePitch('0:1:0', 76);
    tied.changeTie('0:0:3', '0:1:0');
    tied.deleteNotes(['0:1:0']);
    const danglingTie = !!tied.get('0:0:3').node.querySelector('tie, tied');
    const triplet = new ScoreEditor(sampleXML);
    triplet.changeTriplet(['0:0:0', '0:0:1', '0:0:2']);
    triplet.deleteNotes(['0:0:0', '0:0:1', '0:0:2']);
    const tripletEmpty = { mark: !!triplet.parts[0].querySelector('time-modification'), slots: triplet.restPositions(0, { partIndex: 0, voice: '1', staff: '1' }, 1), issues: parseScore(triplet.serialize()).measureIssues };
    const partial = new ScoreEditor(sampleXML);
    partial.changeTriplet(['0:0:0', '0:0:1', '0:0:2']);
    partial.deleteNotes(['0:0:1']);
    partial.changeTriplet(['0:0:0'], true);
    const partialRest = { mark: !!partial.parts[0].querySelector('time-modification'), issues: parseScore(partial.serialize()).measureIssues };
    return { meters, oneUndo, restored, deleted, issues, silentTracks: silent.tracks.length, silentNotes: silent.tracks.flatMap(track => track.notes).length, reinserted, chord, danglingTie, tripletEmpty, partialRest };
  });
  assert.deepEqual(core.meters, [3,4,3,4]);
  assert.equal(core.oneUndo, 1);
  assert.deepEqual(core.restored, [4,4,4,4]);
  assert.deepEqual(core.deleted.map(item => item.rest), [true,false,true,false]);
  assert.deepEqual(core.deleted.map(item => item.start), [0,1,2,3]);
  assert.deepEqual(core.issues, []);
  assert.equal(core.silentTracks, 4);
  assert.equal(core.silentNotes, 0);
  assert.equal(core.reinserted, 1);
  assert.deepEqual(core.chord.notes, [{midi:64,start:0,chord:false},{midi:55,start:0,chord:false}]);
  assert.equal(core.chord.backup, '4');
  assert.deepEqual(core.chord.issues, []);
  assert.equal(core.danglingTie, false);
  assert.equal(core.tripletEmpty.mark, false);
  assert.ok(core.tripletEmpty.slots.includes(0));
  assert.deepEqual(core.tripletEmpty.issues, []);
  assert.equal(core.partialRest.mark, false);
  assert.deepEqual(core.partialRest.issues, []);

  await page.locator('#sample-button').click();
  await page.waitForSelector('#score-view .measure-number-badge');
  await page.locator('#edit-tab').click();
  assert.equal(await page.locator('#mode-measures').getAttribute('aria-pressed'), 'true');
  assert.equal(await page.locator('#note-tools').isVisible(), false);
  const badge = index => page.locator(`.measure-number-badge[data-measure-index="${index}"]`).first();
  await badge(0).click();
  await page.locator('#score-view .vf-stavenote .vf-notehead').nth(8).click({ modifiers: ['Shift'], force: true });
  assert.match(await page.locator('#editor-selection').textContent(), /共 3 小节/);
  await badge(1).click({ modifiers: ['Control'] });
  assert.match(await page.locator('#editor-selection').textContent(), /第 1、3 小节/);
  await page.keyboard.press('Delete');
  assert.equal(await page.locator('#edit-undo').isEnabled(), false, 'Measure mode must not delete notes');
  await page.locator('[data-meter="3/4"]').click();
  await page.locator('#apply-meter').click();
  const ready = () => page.waitForFunction(() => document.querySelector('#editor-message').textContent.includes('已更新') && !document.querySelector('#mode-measures').disabled);
  await ready();
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#edit-download').click();
  const download = await downloadPromise;
  const xml = await readFile(await download.path(), 'utf8');
  const uiMeters = await page.evaluate(async xml => {
    const { ScoreEditor } = await import('/src/editor.js');
    const editor = new ScoreEditor(xml);
    return [0,1,2,3].map(index => editor.meterAt(index).beats);
  }, xml);
  assert.deepEqual(uiMeters, [3,4,3,4]);
  await mkdir('.cache/editor-ui', { recursive: true });
  await page.screenshot({ path: '.cache/editor-ui/measures.png' });
  await page.locator('#edit-undo').click(); await ready();
  await page.locator('#mode-notes').click();
  assert.equal(await page.locator('#measure-tools').isVisible(), false);
  const heads = page.locator('#score-view .vf-stavenote .vf-notehead');
  await heads.first().click({ force: true });
  assert.match(await page.locator('#editor-selection').textContent(), /第 1 小节/);
  const oldPitch = await page.locator('#pitch-current').textContent();
  const pitchPoint = await page.locator('#pitch-staff').evaluate(svg => {
    const p = svg.createSVGPoint(); p.x = 180; p.y = 62;
    const c = p.matrixTransform(svg.getScreenCTM()); return {x:c.x,y:c.y};
  });
  await page.mouse.click(pitchPoint.x, pitchPoint.y);
  const target = await page.locator('#pitch-target').textContent();
  assert.notEqual(target, oldPitch);
  assert.notEqual(target, '—');
  await page.locator('#apply-pitch').click(); await ready();
  assert.equal(await page.locator('#pitch-current').textContent(), target);
  await page.locator('#rhythm-palette button[data-beats="2"]').click(); await ready();
  assert.match(await page.locator('#editor-selection').textContent(), /2 拍/);
  await page.evaluate(() => { window.scrollTo(0,0); document.querySelector('#editor-panel').scrollTop = 0; });
  await page.screenshot({ path: '.cache/editor-ui/notes.png' });
  await heads.nth(1).click({ modifiers: ['Control'], force: true });
  assert.match(await page.locator('#editor-selection').textContent(), /2 个音符/);
  await page.locator('#delete-notes').click(); await ready();
  await page.locator('#note-insert-tool').click();
  await page.locator('#insert-measure').selectOption('2');
  await page.locator('#score-view .vf-stavenote').first().click({ force: true });
  assert.equal(await page.locator('#insert-measure').inputValue(), '0');
  assert.equal(await page.locator('#insert-start').inputValue(), '0');
  assert.equal(await page.locator('#insert-note').isEnabled(), true);
  await page.locator('#insert-rhythm-palette button[data-beats="1"]').click();
  await page.locator('#insert-note').click(); await ready();
  await page.screenshot({ path: '.cache/editor-ui/insert.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '.cache/editor-ui/mobile.png', fullPage: true });
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1);
  assert.equal(overflow, false, 'Mobile page must not overflow horizontally');
  const silentXml = await page.evaluate(async () => {
    const { ScoreEditor } = await import('/src/editor.js');
    const { sampleXML } = await import('/src/sample.js');
    const editor = new ScoreEditor(sampleXML);
    return editor.deleteNotes(editor.records.filter(record => record.pitched).map(record => record.id));
  });
  await page.setViewportSize({ width: 1500, height: 1050 });
  await page.locator('#file-input').setInputFiles({ name: 'silent.musicxml', mimeType: 'application/xml', buffer: Buffer.from(silentXml) });
  await page.waitForFunction(() => document.querySelector('#import-progress').hidden && !!document.querySelector('#score-view svg'));
  assert.equal(await page.locator('#score-view .render-error').count(), 0);
  await badge(0).click();
  assert.equal(await page.locator('#insert-note').isEnabled(), true);
  await page.locator('#insert-note').click(); await ready();
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ core, uiMeters, oldPitch, target, errors, screenshots: '.cache/editor-ui/' }, null, 2));
} finally { await browser.close(); }
