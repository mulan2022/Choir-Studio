import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';

const note = (step, duration, triplet = false, edge = '') => `<note><pitch><step>${step}</step><octave>4</octave></pitch><duration>${duration}</duration><voice>1</voice><type>quarter</type>${triplet ? '<time-modification><actual-notes>3</actual-notes><normal-notes>2</normal-notes></time-modification>' : ''}${edge ? `<notations><tuplet number="1" type="${edge}"/></notations>` : ''}</note>`;
const measure = (index, falseTriplet) => `<measure implicit="no" number="${index + 1}">${index === 0 ? '<attributes><divisions>48</divisions><key><fifths>0</fifths></key><time><beats>4</beats><beat-type>4</beat-type></time><clef><sign>G</sign><line>2</line></clef></attributes>' : ''}${falseTriplet ? `${note('C', 32, true, 'start')}${note('D', 32, true)}${note('E', 32, true, 'stop')}<note><rest/><duration>96</duration><voice>1</voice><type>half</type></note>` : `${note('C', 48)}${note('D', 48)}${note('E', 48)}${note('F', 48)}`}</measure>`;
const xml = `<?xml version="1.0" encoding="utf-8"?><!DOCTYPE score-partwise PUBLIC "-//Recordare//DTD MusicXML 4.0 Partwise//EN" "http://www.musicxml.org/dtds/partwise.dtd"><score-partwise version="4.0"><work><work-title>Triplet Test</work-title></work><movement-title>Triplet Test</movement-title><part-list>${[1, 2].map(i => `<score-part id="P${i}"><part-name>Voice ${i}</part-name><score-instrument id="I${i}"><instrument-name>Voice</instrument-name></score-instrument><midi-instrument id="I${i}"><midi-channel>${i}</midi-channel><midi-program>53</midi-program></midi-instrument></score-part>`).join('')}</part-list>${[1, 2].map(i => `<part id="P${i}">${[0, 1, 2, 3].map(j => measure(j, j < 3)).join('')}</part>`).join('')}</score-partwise>`;

const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:5187/');
  const result = await page.evaluate(async xml => {
    const { ScoreEditor } = await import('/src/editor.js');
    const { parseScore } = await import('/src/score.js');
    const editor = new ScoreEditor(xml);
    editor.changeTriplet(['0:0:1'], true);
    const removedDuration = editor.get('0:0:1').durationUnits / editor.get('0:0:1').divisions;
    const removedMark = !!editor.get('0:0:1').node.querySelector('time-modification');
    editor.changeMeterRange(0, 2, 3, 4);
    const meters = [0, 1, 2, 3].map(index => editor.meterAt(index).beats);
    const afterRange = parseScore(editor.serialize()).measureIssues;
    const beforeInvalid = editor.serialize();
    let rejected = false;
    try { editor.changeMeterRange(2, 1, 3, 4); } catch { rejected = true; }
    const unchanged = beforeInvalid === editor.serialize();
    editor.undo();
    const undone = [0, 1, 2, 3].map(index => editor.meterAt(index).beats);
    editor.redo();
    editor.changeTriplet(['0:1:1'], true);
    const afterAnotherRemove = parseScore(editor.serialize()).measureIssues;
    editor.changeTriplet(['0:3:0', '0:3:1', '0:3:2']);
    const added = [0, 1, 2].map(index => ({ duration: editor.get(`0:3:${index}`).durationUnits / editor.get(`0:3:${index}`).divisions, mark: !!editor.get(`0:3:${index}`).node.querySelector('time-modification') }));
    const afterAdd = parseScore(editor.serialize()).measureIssues;
    editor.changeTriplet(['0:3:1'], true);
    const afterAddRemove = parseScore(editor.serialize()).measureIssues;
    const regularDurations = [0, 1, 2].map(index => editor.get(`0:3:${index}`).durationUnits / editor.get(`0:3:${index}`).divisions);
    const bare = new ScoreEditor(xml.replace('<note><rest/><duration>96</duration><voice>1</voice><type>half</type></note>', ''));
    bare.changeTriplet(['0:0:0'], true);
    const bareAfterRemove = bare.voiceGroups(0, 0).get('1:1').map(record => record.durationUnits / record.divisions);
    bare.changeMeterRange(0, 0, 3, 4);
    const bareIssues = parseScore(bare.serialize()).measureIssues;
    return { removedDuration, removedMark, meters, afterRange, rejected, unchanged, undone, afterAnotherRemove, added, afterAdd, afterAddRemove, regularDurations, bareAfterRemove, bareIssues };
  }, xml);
  assert.equal(result.removedDuration, 1);
  assert.equal(result.removedMark, false);
  assert.deepEqual(result.meters, [3, 3, 3, 4]);
  assert.deepEqual(result.afterRange, []);
  assert.equal(result.rejected, true);
  assert.equal(result.unchanged, true);
  assert.deepEqual(result.undone, [4, 4, 4, 4]);
  assert.deepEqual(result.afterAnotherRemove, []);
  assert.deepEqual(result.added, Array.from({ length: 3 }, () => ({ duration: 2 / 3, mark: true })));
  assert.deepEqual(result.afterAdd, []);
  assert.deepEqual(result.afterAddRemove, []);
  assert.deepEqual(result.regularDurations, [1, 1, 1]);
  assert.deepEqual(result.bareAfterRemove, [1, 1, 1, 1]);
  assert.deepEqual(result.bareIssues, []);
  await page.locator('#file-input').setInputFiles({ name: 'triplets.musicxml', mimeType: 'application/xml', buffer: Buffer.from(xml) });
  await page.locator('#loaded').waitFor({ state: 'visible' });
  await page.waitForFunction(() => !!document.querySelector('#score-view svg, #score-view .render-error'), { timeout: 30000 });
  assert.equal(await page.locator('#score-view .render-error').count(), 0, await page.locator('#score-view').textContent());
  await page.locator('#edit-tab').click();
  assert.equal(await page.locator('#meter-start').inputValue(), '1');
  assert.equal(await page.locator('#meter-end').inputValue(), '1');
  await page.locator('#meter-end').fill('3');
  await page.locator('#select-measure-range').click();
  await page.locator('#edit-beats').fill('3');
  await page.locator('#apply-meter').click();
  await page.waitForFunction(() => document.querySelector('#editor-message')?.textContent?.includes('已更新'), { timeout: 30000 });
  assert.equal(await page.locator('#score-view .render-error').count(), 0, await page.locator('#score-view').textContent());
  assert.ok(await page.locator('#score-view svg .vf-stavenote .vf-notehead').count(), await page.locator('#score-view').textContent());
  await page.locator('#mode-notes').click();
  await page.locator('#score-view svg .vf-stavenote .vf-notehead').first().click({ force: true });
  assert.equal(await page.locator('#remove-triplet').isEnabled(), true);
  await page.locator('#remove-triplet').click();
  await page.waitForFunction(() => document.querySelector('#editor-message')?.textContent?.includes('已更新'), { timeout: 30000 });
  const heads = page.locator('#score-view svg .vf-stavenote .vf-notehead');
  await heads.nth(0).click({ force: true });
  await heads.nth(1).click({ modifiers: ['Control'], force: true });
  await heads.nth(2).click({ modifiers: ['Control'], force: true });
  assert.equal(await page.locator('#add-triplet').isEnabled(), true);
  await page.locator('#add-triplet').click();
  await page.waitForFunction(() => document.querySelector('#editor-message')?.textContent?.includes('已更新'), { timeout: 30000 });
  assert.deepEqual(errors, []);
  console.log(result);
} finally { await browser.close(); }
